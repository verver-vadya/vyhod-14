// Кириллица, которая пишется как латиница
const SAME: Record<string, string> = { А: "A", В: "B", Е: "E", К: "K", М: "M", Н: "H", О: "O", Р: "P", С: "C", Т: "T", Х: "X" };
for (const [cyr, lat] of Object.entries(SAME)) G[cyr] = G[lat];

export const LED_CHARS = Object.keys(G);

// Горящие точки знака одной строкой SVG-пути: подряд идущие точки в ряду — один прямоугольник
export function glyphPath(ch: string) {
  const rows = (G[ch] ?? G[" "]).split("|");
  let d = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < 5; x++) {
      if (row[x] !== "#") continue;
      let w = 1;
      while (x + w < 5 && row[x + w] === "#") w++;
      d += `M${x} ${y}h${w}v1h-${w}z`;
      x += w - 1;
    }
  });
  return d;
}

// Знак, которого нет в шрифте, на табло горит пустым
export const ledChar = (ch: string) => (ch in G ? ch : " ");
